// Generates Dart bindings for the few UIKit / Foundation APIs the app calls
// directly instead of going through a platform channel.
//
// Run from apps/mobile: dart run tool/ffigen.dart
import 'package:ffigen/ffigen.dart';

/// Interfaces to bind, and the only selectors kept on each (including the
/// ones declared in their categories).
const _selectors = {
  'NSProcessInfo': {'processInfo', 'isiOSAppOnMac'},
  'UIDevice': {'currentDevice', 'userInterfaceIdiom'},
};

void main() {
  FfiGenerator(
    input: Input(
      entryPoints: [
        iosSdkUri.resolve(
          'System/Library/Frameworks/Foundation.framework/Headers/NSProcessInfo.h',
        ),
        iosSdkUri.resolve(
          'System/Library/Frameworks/UIKit.framework/Headers/UIDevice.h',
        ),
      ],
      compilerOptions: ['-isysroot', iosSdkPath, '-miphoneos-version-min=15.0'],
      appendCompilerOptions: true,
    ),
    objectiveC: const ObjectiveC(),
    output: Output(
      dart: DartOutput(
        path: Uri.file('lib/services/native/ios_environment_bindings.g.dart'),
      ),
      preamble: '// Generated by tool/ffigen.dart. Do not edit.\n',
    ),
    visitors: [
      Visitor(
        objCInterface: (node) {
          if (_selectors.containsKey(node.name)) node.isIncluded = true;
        },
        objCMethod: (node) {
          node.isIncluded = _selectors.values.any(
            (selectors) => selectors.contains(node.selector),
          );
        },
        enumClass: (node) {
          if (node.name == 'UIUserInterfaceIdiom') {
            node.isIncluded = true;
            // NS_ENUM(NSInteger): the underlying type is fixed.
            node.silenceWarning = true;
          }
        },
      ),
    ],
  ).generate();
}
