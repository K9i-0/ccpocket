#!/usr/bin/env bash
# Reproduces every TLC run recorded in NOTES.md.
#   bash formal/permission-flow/tlaplus/run.sh            # all runs
#   bash formal/permission-flow/tlaplus/run.sh 'P1a*'     # runs whose name matches the glob
# Each run writes cfg/<name>.cfg (generated) and out/<name>.txt (raw TLC output).
# out/SUMMARY.txt gets one line per run: verdict, states, depth, time, constants.
# For a violated INVARIANT the states/depth are those of the 1-worker rerun.
# "BASE" in the disabled column is the default set defined below.
# TLC exits non-zero when it finds a violation, so there is no `set -e` here.
set -u

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
JAR="$HERE/../../.tools/tla/tla2tools.jar"
FILTER="${1:-*}"
cd "$HERE" || exit 1
mkdir -p cfg out states

# Environment behaviours that are off unless a run turns them on (see NOTES.md):
#   lateCanUse  canUseTool arriving after the query is gone
#   bgTool      canUseTool while the CLI is between turns (background subagent)
#   bgFrame     main-agent assistant/user frames between turns
BASE='"lateCanUse", "bgTool", "bgFrame"'

SUMMARY="$HERE/out/SUMMARY.txt"
[ "$FILTER" = "*" ] && : > "$SUMMARY"

# run NAME KIND PROP [KEY=VALUE ...]
#   KIND: INVARIANT | PROPERTY      PROP: operator name in PermissionFlow.tla
#   keys: SPEC IDS MODES MAXQ MAXCHAIN M1 M2 M3 DISABLED GATED
run() {
  local name="$1" kind="$2" prop="$3"; shift 3
  # shellcheck disable=SC2254
  case "$name" in $FILTER) ;; *) return 0 ;; esac
  local SPEC=Spec IDS='t1, t2' MODES='"default", "plan"' MAXQ=2 MAXCHAIN=2
  local M1=FALSE M2=FALSE M3=FALSE DISABLED="$BASE" GATED=FALSE
  local kv
  for kv in "$@"; do
    case "$kv" in
      SPEC=*) SPEC="${kv#*=}" ;; IDS=*) IDS="${kv#*=}" ;; MODES=*) MODES="${kv#*=}" ;;
      MAXQ=*) MAXQ="${kv#*=}" ;; MAXCHAIN=*) MAXCHAIN="${kv#*=}" ;;
      M1=*) M1="${kv#*=}" ;; M2=*) M2="${kv#*=}" ;; M3=*) M3="${kv#*=}" ;;
      DISABLED=*) DISABLED="${kv#*=}" ;; GATED=*) GATED="${kv#*=}" ;;
      *) echo "unknown key: $kv" >&2; return 1 ;;
    esac
  done
  cat > "cfg/$name.cfg" <<EOF
\\* generated by run.sh
CONSTANTS
  Ids = {$IDS}
  Modes = {$MODES}
  InitMode = "default"
  MaxQueue = $MAXQ
  MaxChain = $MAXCHAIN
  NONE = NONE
  M1 = $M1
  M2 = $M2
  M3 = $M3
  Disabled = {$DISABLED}
  ClientGated = $GATED
SPECIFICATION $SPEC
$kind $prop
EOF
  rm -rf "states/$name"
  java -XX:+UseParallelGC -cp "$JAR" tlc2.TLC -config "cfg/$name.cfg" -workers auto \
    -metadir "states/$name" PermissionFlow.tla > "out/$name.txt" 2>&1
  local verdict
  if grep -q "No error has been found" "out/$name.txt"; then verdict="holds"
  elif grep -q "violated" "out/$name.txt"; then verdict="VIOLATED"
  else verdict="ERROR"; fi
  if [ "$verdict" = VIOLATED ] && [ "$kind" = INVARIANT ]; then
    # With several workers the reported trace differs from run to run. One
    # worker gives a shortest counterexample, the same one every time.
    rm -rf "states/$name"
    java -XX:+UseParallelGC -cp "$JAR" tlc2.TLC -config "cfg/$name.cfg" -workers 1 \
      -metadir "states/$name" PermissionFlow.tla > "out/$name.txt" 2>&1
  fi
  local stats
  stats="$(grep -E "distinct states found, 0 states left|^[0-9]+ states generated" "out/$name.txt" | tail -1)"
  local depth
  depth="$(grep -E "depth of the complete state graph" "out/$name.txt" | sed -E 's/.*is ([0-9]+).*/\1/')"
  local time
  time="$(grep -E "^Finished in" "out/$name.txt" | sed -E 's/Finished in ([^ ]+).*/\1/')"
  local dis
  case "$DISABLED" in
    "$BASE") dis=BASE ;;
    "$BASE, "*) dis="BASE + ${DISABLED#"$BASE, "}" ;;
    *) dis="$DISABLED" ;;
  esac
  printf '%-18s %-15s %-8s | %s | depth=%s | %s | spec=%s ids={%s} modes={%s} maxQ=%s maxChain=%s M1=%s M2=%s M3=%s gated=%s disabled={%s}\n' \
    "$name" "$prop" "$verdict" "$stats" "${depth:-n/a}" "${time:-?}" \
    "$SPEC" "$IDS" "$MODES" "$MAXQ" "$MAXCHAIN" "$M1" "$M2" "$M3" "$GATED" "$dis" \
    | tee -a "$SUMMARY"
  rm -rf "states/$name"
}

# ---------------------------------------------------------------------------
# 0. Sanity: types, and reachability probes that are EXPECTED to be violated.
run TypeOK            INVARIANT TypeOK
run Probe-TwoPending  INVARIANT ProbeTwoPending
run Probe-Chain2      INVARIANT ProbeChain2
run Probe-OldChain2   INVARIANT ProbeOldChain2
run Probe-Queue2      INVARIANT ProbeQueue2
run Probe-StaleRes    INVARIANT ProbeStaleRes

# RUNS-BEGIN
# 1. Baseline (current code, M1=M2=M3=FALSE), one property per run.
run P1a   INVARIANT P1a
run P1b   INVARIANT P1b
run P2    INVARIANT P2
run P3    INVARIANT P3
run P4    INVARIANT P4
run P4n   INVARIANT P4n
run P5    INVARIANT P5
run P6    INVARIANT P6
run E1    INVARIANT E1
run E2    INVARIANT E2

# 2. Baseline, repeated with the already-found cause switched off, to enumerate
#    the distinct ways each failing property is violated.
B="$BASE"
run P1a-x1 INVARIANT P1a DISABLED="$B, \"statusWhilePending\""
run P1b-x1 INVARIANT P1b DISABLED="$B, \"preAbort\""
run P3-x1  INVARIANT P3  DISABLED="$B, \"preAbort\""
run P3-x2  INVARIANT P3  DISABLED="$B, \"reentrant\""
run P4-x1  INVARIANT P4  DISABLED="$B, \"preAbort\""
run P5-x1  INVARIANT P5  DISABLED="$B, \"inputWhenDead\""
run E1-x1  INVARIANT E1  DISABLED="$B, \"inputWhenDead\""
run E2-x1  INVARIANT E2  DISABLED="$B, \"inputWhenDead\""
run P1a-x2 INVARIANT P1a DISABLED="$B, \"statusWhilePending\", \"naturalEnd\""
run P1b-x2 INVARIANT P1b DISABLED="$B, \"preAbort\", \"interrupt\""
run P4-x2  INVARIANT P4  DISABLED="$B, \"preAbort\", \"interrupt\", \"abort\""
run E1-x2  INVARIANT E1  DISABLED="$B, \"naturalEnd\""
run E2-x2  INVARIANT E2  DISABLED="$B, \"naturalEnd\""
run P1b-x3 INVARIANT P1b DISABLED="$B, \"preAbort\", \"interrupt\", \"abort\""

# 3. Liveness (no symmetry, no state constraint).  Mode changes are irrelevant
#    to P7/P8, so these runs use one mode and MaxChain=0 to keep the graph small.
L='MODES="default"'
run P7       PROPERTY P7 SPEC=P7Spec "$L" MAXCHAIN=0
run P8       PROPERTY P8 SPEC=P8Spec "$L" MAXCHAIN=0
run P8-x1    PROPERTY P8 SPEC=P8Spec "$L" MAXCHAIN=0 DISABLED="$B, \"naturalEnd\""
run P8-x2    PROPERTY P8 SPEC=P8Spec "$L" MAXCHAIN=0 DISABLED="$B, \"restart\""
# Short lasso for the notes: one id, side paths off.
run P8-min   PROPERTY P8 SPEC=P8Spec "$L" MAXCHAIN=0 IDS=t1 DISABLED="$B, \"reentrant\", \"preAbort\", \"abort\", \"crash\", \"sdkMode\", \"interrupt\""

# 3b. Which fairness assumptions are needed: drop one at a time.
run P7-noHandler  PROPERTY P7 SPEC=P7NoHandler  "$L" MAXCHAIN=0
run P7-noRecv     PROPERTY P7 SPEC=P7NoRecv     "$L" MAXCHAIN=0
run P7-noDecide   PROPERTY P7 SPEC=P7NoDecide   "$L" MAXCHAIN=0
run P7-weakExists PROPERTY P7 SPEC=P7WeakExists "$L" MAXCHAIN=0
NE="$B, \"naturalEnd\""
run P8-noHandler  PROPERTY P8 SPEC=P8NoHandler  "$L" MAXCHAIN=0 DISABLED="$NE"
run P8-noPull     PROPERTY P8 SPEC=P8NoPull     "$L" MAXCHAIN=0 DISABLED="$NE"
run P8-noResult   PROPERTY P8 SPEC=P8NoResult   "$L" MAXCHAIN=0 DISABLED="$NE"

# 4. Larger bounds for the properties that hold on the baseline.
run P2-3ids   INVARIANT P2  IDS="t1, t2, t3" "$L" MAXCHAIN=0
run P4n-3ids  INVARIANT P4n IDS="t1, t2, t3" "$L" MAXCHAIN=0
run P6-chain3 INVARIANT P6  IDS=t1 MODES='"default", "plan", "acceptEdits"' MAXCHAIN=3
run P7-3ids   PROPERTY  P7  SPEC=P7Spec IDS="t1, t2, t3" "$L" MAXCHAIN=0 MAXQ=1

# 5. SDK behaviours the Bridge code cannot rule out, switched on one at a time.
run late-P5   INVARIANT P5  DISABLED='"bgTool", "bgFrame"'
run late-P2   INVARIANT P2  DISABLED='"bgTool", "bgFrame"'
run bgTool-P8 PROPERTY  P8  SPEC=P8Spec "$L" MAXCHAIN=0 DISABLED='"lateCanUse", "bgFrame", "naturalEnd"'
run bgTool-P7 PROPERTY  P7  SPEC=P7Spec "$L" MAXCHAIN=0 DISABLED='"lateCanUse", "bgFrame"'
run bgFrame-P8 PROPERTY P8  SPEC=P8Spec "$L" MAXCHAIN=0 DISABLED='"lateCanUse", "bgTool", "naturalEnd"'

# 6. Extra experiment: the mobile client only offers a request while it sees
#    waiting_approval (apps/mobile/lib/features/chat_session/permission_transcript.dart:61-73).
run gated-P7  PROPERTY  P7  SPEC=P7Spec "$L" MAXCHAIN=0 GATED=TRUE
run gated-P7-x1 PROPERTY P7 SPEC=P7Spec "$L" MAXCHAIN=0 GATED=TRUE DISABLED="$B, \"statusWhilePending\", \"naturalEnd\""

# 7. Seeded regressions.  A regression counts as caught only by a property that
#    holds on the baseline: P2, P4n, P6, P7, P8 (P8 with naturalEnd off, as in P8-x1).
for m in M1 M2 M3; do
  run $m-P2  INVARIANT P2  $m=TRUE
  run $m-P4n INVARIANT P4n $m=TRUE
  run $m-P6  INVARIANT P6  $m=TRUE
  run $m-P7  PROPERTY  P7  SPEC=P7Spec "$L" MAXCHAIN=0 $m=TRUE
  run $m-P8  PROPERTY  P8  SPEC=P8Spec "$L" MAXCHAIN=0 $m=TRUE DISABLED="$NE"
done
# M3 with a single queued update: not caught (see NOTES.md).
run M3-P6-chain1 INVARIANT P6 M3=TRUE MAXCHAIN=1
# RUNS-END

# 8. Counterexamples as JSON (tla2tools 1.7.4 has no -dumpTrace, so the text
#    trace is converted), random behaviours from TLC -simulate, and a replay of
#    both on the real SdkProcess (replay/replay.test.ts).
if [ "$FILTER" = "*" ] && command -v node >/dev/null 2>&1; then
  rm -f out/trace-*.json out/other-*.json out/sim-*.json
  # trace-*: baseline counterexamples and probes; these are replayed.
  for n in P1a P1a-x1 P1b P1b-x1 P1b-x2 P3 P4 P4-x2 P5 E1 E1-x1 E2-x1 \
           Probe-TwoPending Probe-Chain2 Probe-OldChain2 Probe-Queue2 Probe-StaleRes; do
    node trace2json.mjs "out/$n.txt" "out/trace-$n.json"
  done
  # other-*: lassos, mutants (the code is not mutated) and SDK-dependent runs; not replayed.
  for n in P8 P8-min gated-P7 late-P5 bgTool-P8 bgFrame-P8 M1-P2 M1-P7 M2-P4n M3-P6 \
           P7-noHandler P7-noRecv P7-noDecide P8-noHandler P8-noPull P8-noResult; do
    node trace2json.mjs "out/$n.txt" "out/other-$n.json"
  done
  # Random behaviours: every simulation run that reaches ProbeSim prints its trace.
  sim() { # NAME NUM SEED MAXCHAIN DISABLED
    cat > "cfg/$1.cfg" <<EOF
\\* generated by run.sh: random behaviours for the replay (TLC -simulate)
CONSTANTS
  Ids = {t1, t2}
  Modes = {"default", "plan"}
  InitMode = "default"
  MaxQueue = 2
  MaxChain = $4
  NONE = NONE
  M1 = FALSE
  M2 = FALSE
  M3 = FALSE
  Disabled = {$5}
  ClientGated = FALSE
SPECIFICATION Spec
INVARIANT ProbeSim
EOF
    java -cp "$JAR" tlc2.TLC -simulate "num=$2" -depth 60 -seed "$3" -continue -workers 1 \
      -config "cfg/$1.cfg" -metadir "states/$1" PermissionFlow.tla > "out/$1.txt" 2>&1
    rm -rf "states/$1"
    node trace2json.mjs --multi "out/$1.txt" "out/$1-traces.json"
  }
  sim sim 6000 1 2 "$BASE"          # everything on (restarts, crashes, mode changes)
  # no restart/stop/crash/natural end: longer turns
  sim sim-turns 120 2 1 "$BASE, \"restart\", \"crash\", \"stop\", \"naturalEnd\", \"sdkMode\""
  VITEST="$HERE/../../../packages/bridge/node_modules/.bin/vitest"
  if [ -x "$VITEST" ]; then
    (cd "$HERE/../../.." && "$VITEST" run --config "$HERE/replay/vitest.config.mjs") \
      2>&1 | grep -v '^\[sdk-process\]' > out/replay.txt
    grep -E "Tests|Test Files|AssertionError" out/replay.txt
    node -e 'const fs=require("fs");for(const f of fs.readdirSync("out").filter(f=>/^sim.*traces\.json$/.test(f))){const t=JSON.parse(fs.readFileSync("out/"+f));console.log(f+": "+t.length+" traces, "+t.reduce((n,x)=>n+x.length,0)+" states")}' | tee -a out/replay.txt
  else
    echo "vitest not installed (npm install in the repo root): replay skipped" | tee out/replay.txt
  fi
fi

rmdir states 2>/dev/null
echo "summary: $SUMMARY"
