#!/usr/bin/env python3
"""Write a copy of a spec without the named properties (the @requirement line
and the property block are removed; nothing else changes).
usage: strip_props.py BASE.fsl OUT.fsl NAME [NAME ...]"""
import re, sys
base, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
s = open(base).read()
for n in names:
    pat = r"(?:[ \t]*@requirement\([^\n]*\n)?[ \t]*(?:invariant|leadsTo)\s+%s\s*\{.*?\n  \}\n\n?" % re.escape(n)
    s, k = re.subn(pat, "", s, count=1, flags=re.S)
    if k != 1:
        sys.exit("property %s not found" % n)
s = s.replace("spec PermissionFlow {", "// GENERATED by tools/strip_props.py: properties removed = %s\nspec PermissionFlow {" % ", ".join(names), 1)
open(out, "w").write(s)
