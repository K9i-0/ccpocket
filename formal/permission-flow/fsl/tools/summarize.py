#!/usr/bin/env python3
"""Read the raw verifier JSON under OUT and print the result tables.
usage: summarize.py OUT"""
import glob, json, os, sys

out = sys.argv[1]

def load(path):
    try:
        return json.load(open(path))
    except Exception:
        return None

def verdict(d, name=None):
    if d is None:
        return "(no output)"
    r = d.get("result")
    if r == "violated":
        what = d.get("invariant")
        kind = d.get("violation_kind")
        step = d.get("violated_at_step")
        tag = kind if (name is None or what == name) else "%s of %s" % (kind, what)
        if kind == "leadsTo":
            return "violated (lasso: pending since step %s, loop from step %s)" % (d.get("pending_since"), d.get("loop_start"))
        return "violated (%s, step %s)" % (tag, step)
    if r == "verified":
        return "verified to depth %s (bounded)" % d.get("checked_to_depth")
    if r == "proved":
        return "proved (unbounded)"
    if r == "unknown_cti":
        return "unknown_cti (%s%s)" % (d.get("invariant"), ", " + d["rank_failure"] if d.get("rank_failure") else "")
    if r == "error":
        return "error: %s" % str(d.get("message"))[:90]
    return str(r)

def trace(d):
    steps = []
    for st in d.get("trace", []):
        a = st.get("action")
        if a:
            steps.append("%s(%s)" % (a["name"], ",".join("%s=%s" % kv for kv in sorted(a["params"].items()))))
    return " -> ".join(steps)

def table(title, directory, show_trace=False):
    files = sorted(glob.glob(os.path.join(directory, "*.bmc.json")))
    files = [f for f in files if not os.path.basename(f).startswith("unfiltered")]
    if not files:
        return
    print("\n== %s  [%s]" % (title, directory))
    order = ["P1a", "P1b", "P2", "P3", "P4a", "P4b", "P4c", "P5a", "P5b", "P6", "P7", "P8", "Aux", "Fix"]
    def key(f):
        n = os.path.basename(f)
        for i, o in enumerate(order):
            if n.startswith(o + "_") or n.startswith(o):
                return (i, n)
        return (99, n)
    for f in sorted(files, key=key):
        name = os.path.basename(f).split(".")[0]
        d = load(f)
        print("  %-36s %s" % (name, verdict(d, name)))
        if show_trace and d and d.get("result") == "violated":
            print("      " + trace(d))

print("FSL evaluation summary (generated by tools/summarize.py from the raw JSON in out/)")
table("Current-code model, every property on its own", os.path.join(out, "current"), True)

print("\n== Unbounded proofs  [%s/proof]" % out)
for f in sorted(glob.glob(os.path.join(out, "proof", "*.json"))):
    d = load(f)
    line = verdict(d)
    if d and d.get("result") == "proved":
        user = [i for i in d.get("invariants_checked", []) if not i.startswith("_bounds_")]
        line += "; invariants: " + ", ".join(user)
    if d and d.get("result") in ("verified", "unknown_budget"):
        line += " closure=%s states=%s" % (d.get("closure"), d.get("states_explored", d.get("states")))
    print("  %-42s %s" % (os.path.basename(f), line))

for d in sorted(glob.glob(os.path.join(out, "attribution", "*"))):
    table("All hypothetical fixes except %s" % os.path.basename(d).replace("all_but_", ""), d, True)
table("All hypothetical fixes on", os.path.join(out, "fix_all"))
for d in sorted(glob.glob(os.path.join(out, "seeded", "*"))):
    table("Seeded regression %s" % os.path.basename(d), d, True)
for d in sorted(glob.glob(os.path.join(out, "liveness", "*"))):
    if os.path.isdir(d):
        table("Liveness: %s" % os.path.basename(d), d, True)
print("\n== Liveness extras  [%s/liveness]" % out)
for f in sorted(glob.glob(os.path.join(out, "liveness", "deeper", "*.json")) + glob.glob(os.path.join(out, "liveness", "*.json"))):
    print("  %-42s %s" % (os.path.basename(f), verdict(load(f))))
for d in sorted(glob.glob(os.path.join(out, "env", "*"))):
    table("Environment relaxation %s" % os.path.basename(d), d, True)

print("\n== Mutation analysis  [%s/mutate]" % out)
import collections, re
def mutant_group(target):
    if target.startswith("const H_") or target.startswith("const E_"):
        return "switch constants (H_*/E_*)"
    if target.startswith("type ") or target.startswith("const "):
        return "type bounds / other constants"
    if target.startswith("init"):
        return "init"
    return "action " + target.split()[0]
for f in sorted(glob.glob(os.path.join(out, "mutate", "*.progress.txt"))):
    base = f[:-len(".progress.txt")]
    d = load(base + ".json")
    rows = []
    for line in open(f):
        m = re.match(r"mutate \[(\d+)/(\d+)\] (\S+) (.*?): (killed|survived|invalid|inconclusive|error)(?: (\S+))?", line)
        if m:
            rows.append((m.group(3), m.group(4), m.group(5), m.group(6)))
    total_planned = None
    m = re.search(r"mutate \[\d+/(\d+)\]", open(f).read())
    if m:
        total_planned = int(m.group(1))
    killed = sum(1 for r in rows if r[2] == "killed")
    survived = sum(1 for r in rows if r[2] == "survived")
    complete = d is not None and "summary" in d
    label = "complete" if complete else "PARTIAL (run did not finish; counted from the progress log)"
    rate = (killed / (killed + survived)) if killed + survived else 0
    print("  %s: %s" % (os.path.basename(base), label))
    print("    judged=%d of %s  killed=%d  survived=%d  kill_rate=%.4f" % (len(rows), total_planned, killed, survived, rate))
    if complete:
        print("    fslc summary: %s" % json.dumps(d["summary"]["by_source"]["builtin"]))
        print("    by requirement: %s" % json.dumps(d.get("by_requirement")))
    groups = collections.OrderedDict()
    for op, target, status, killer in rows:
        g = groups.setdefault(mutant_group(target), [0, 0])
        g[0 if status == "killed" else 1] += 1
    print("    by location (killed/survived):")
    for g, (k, sv) in groups.items():
        print("      %-44s %3d / %3d" % (g, k, sv))
    if complete:
        # which kind of line the mutant touched (mutually exclusive classes)
        spec_path = os.path.join(os.path.dirname(os.path.abspath(out)), "variants", os.path.basename(base).split(".")[0] + ".fsl")
        try:
            src = open(spec_path).read().split("\n")
        except Exception:
            src = None
        if src:
            named = {"status": "status", "settles": "settles", "clientSees": "clientSees",
                     "queue": "queue/parked/waiterStale", "parked": "queue/parked/waiterStale", "waiterStale": "queue/parked/waiterStale",
                     "prom": "prom/pend/sdkInflight", "pend": "prom/pend/sdkInflight", "sdkInflight": "prom/pend/sdkInflight"}
            for v in ("mode", "opPhase", "opMode", "opStale", "opAfter", "opQiChanged", "lastModeWriteStale"):
                named[v] = "mode updates (mode, op*, lastModeWriteStale)"
            cls = collections.OrderedDict()
            for mnt in d["mutants"]:
                if mnt["status"] not in ("killed", "survived"):
                    continue
                loc = mnt.get("loc")
                line = src[loc["line"] - 1] if loc else mnt["target"]
                if mnt["op"].startswith("requires") or line.strip().startswith("requires"):
                    key = "requires clauses"
                elif "H_" in line or "E_PROMPT" in line or mnt["target"].startswith("const"):
                    key = "switch scaffolding (H_*/E_* constants and lines reading them)"
                elif mnt["op"].startswith("type_bound"):
                    key = "type bounds"
                else:
                    mm = re.match(r"\s*(if .*\{ )?(\w+)(\[[^\]]*\])? = ", line)
                    key = named.get(mm.group(2), "other") if mm else "other"
                c = cls.setdefault(key, [0, 0])
                c[0 if mnt["status"] == "killed" else 1] += 1
            print("    by kind of mutated line (killed/survived):")
            for key, (k, sv) in sorted(cls.items(), key=lambda kv: -(kv[1][0] + kv[1][1])):
                print("      %-66s %3d / %3d" % (key, k, sv))
            sc = cls.get("switch scaffolding (H_*/E_* constants and lines reading them)", [0, 0])
            k2, s2 = killed - sc[0], survived - sc[1]
            print("    kill rate without the switch scaffolding lines: %d / %d = %.3f" % (k2, k2 + s2, k2 / (k2 + s2)))
    killers = collections.Counter(r[3] for r in rows if r[2] == "killed")
    print("    killers: %s" % ", ".join("%s=%d" % kv for kv in killers.most_common()))

print("\n== Spec -> implementation  [%s/testgen, %s/sketch]" % (out, out))
d = load(os.path.join(out, "testgen", "scenarios.current_holding.json"))
if d:
    kinds = {}
    for sc in d.get("scenarios", []):
        kinds[sc.get("kind")] = kinds.get(sc.get("kind"), 0) + 1
    print("  scenarios: %s" % kinds)
d = load(os.path.join(out, "testgen", "testgen.vitest.json"))
if d:
    print("  testgen: %s -> %s" % (d.get("result"), d.get("output")))
p = os.path.join(out, "sketch", "vitest-run.txt")
if os.path.exists(p):
    for line in open(p):
        if line.strip().startswith("Tests"):
            print("  counterexample replay on real SdkProcess:" + line.rstrip())
