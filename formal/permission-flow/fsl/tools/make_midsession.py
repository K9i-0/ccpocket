#!/usr/bin/env python3
"""Copy of a spec whose init is a mid-session state: session started, SDK input
stream parked, one prompt in flight, status running. It is the state reached by
  start -> sdk_pull -> client_input -> sdk_pull
except that the mode-update bookkeeping flags (opStale, opQiChanged) keep their
initial value false; they are don't-care while both update slots are Free.
All invariants of the holding subset are proved by induction from this init too.
Used only for `fslc mutate`: permission-flow behaviour then starts at step 1
instead of step 4-5, so a depth-4 mutation run exercises
request -> announce -> answer -> follow-up.
usage: make_midsession.py IN.fsl OUT.fsl"""
import sys
s = open(sys.argv[1]).read()
def rep(old, new):
    global s
    assert s.count(old) == 1, old
    s = s.replace(old, new)
rep("  init {\n    status = Idle\n", "  init {\n    status = Running\n")
rep("    parked = false\n    waiterStale = false\n    stopped = false\n    hasQuery = false\n", "    parked = true\n    waiterStale = false\n    stopped = false\n    hasQuery = true\n")
rep("    sdkInflight = 0\n    forall t: Tool { clientSees[t] = false }\n", "    sdkInflight = 1\n    forall t: Tool { clientSees[t] = false }\n")
s = s.replace("spec PermissionFlow {", "// GENERATED by tools/make_midsession.py: init = mid-session state (see tools/make_midsession.py)\nspec PermissionFlow {", 1)
open(sys.argv[2], "w").write(s)
